'use strict';
const assert=require('node:assert/strict');
const D=require('../dist/data.js'),C=require('../dist/engine.js');
const save=C.freshSave();save.shards=5000;
for(const id of ['kinetic_link','feedback_link','pulse_link'])assert.equal(C.purchase(save,id),false);
for(const id of ['width','rotation','charge','perfect','initial'])assert.equal(C.purchase(save,id),true);
for(const id of ['kinetic_link','feedback_link','pulse_link'])assert.equal(C.purchase(save,id),true);
assert.equal(C.purchase(save,'kinetic_link'),false);
const loaded=C.validateSave(JSON.parse(JSON.stringify(save)));
assert.equal(loaded.tech.kinetic_link,1);
assert.equal(loaded.tech.feedback_link,1);
assert.equal(loaded.tech.pulse_link,1);
const baseSave=C.validateSave(JSON.parse(JSON.stringify(loaded)));
baseSave.tech.kinetic_link=0;baseSave.tech.feedback_link=0;baseSave.tech.pulse_link=0;
const base=new C.Engine(baseSave,{seed:3});
const linked=new C.Engine(loaded,{seed:3});
assert.ok(Math.abs(linked.width-base.width-4*C.RAD)<1e-9);
assert.equal(linked.overloadCost,18);
linked.tactic='volley';assert.equal(linked.overloadCost,28);
linked.reflect({angle:0},{perfect:true});
base.reflect({angle:0},{perfect:true});
assert.ok(Math.abs(linked.energy-base.energy-2)<1e-9,'feedback adds exactly 2 energy');
const skill=new C.Engine(loaded,{mode:'skill',seed:3});
assert.equal(skill.width,55*C.RAD);
assert.equal(skill.overloadCost,20);
const training=new C.Engine(loaded,{training:{boss:0,phase:0},seed:3});
assert.equal(training.width,55*C.RAD);
assert.equal(training.overloadCost,20);
const legacy=C.freshSave();legacy.currentBalance='1.10';legacy.tech={width:1,rotation:1};legacy.records.classic=[{score:100,time:20,balance:'1.10',id:'old',date:'2026-01-01'}];
const migrated=C.validateSave(legacy);
assert.equal(migrated.tech.width,1);
assert.equal(migrated.tech.rotation,1);
assert.equal(migrated.records.classic.length,0);
assert.equal(migrated.recordsArchive.classic.length,1);
assert.equal(D.tech.filter(t=>t.category==='Связи').length,3);
console.log('Linked research, purchase gates, effects, modes and old-save migration passed.');
